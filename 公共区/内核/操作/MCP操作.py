"""
MCP操作 — 按需连接MCP服务

用户说"连接3dsmax"时AI调用此操作，自动安装环境并连接。
启动时不自动安装，避免不必要的等待。
"""
from 操作.基类 import 操作基类, 操作结果


class 连接MCP服务(操作基类):
    """按需连接MCP服务（自动安装环境+连接+发现工具）"""

    名称 = "连接MCP服务"
    描述 = "连接指定的MCP服务，自动安装所需环境（uv、依赖、插件等）。支持的服务名见MCP服务.json配置。"
    参数结构 = {
        "服务名": {
            "类型": "字符串",
            "必填": True,
            "说明": "要连接的MCP服务名称，如3dsmax、filesystem等"
        }
    }

    def 执行(self, 参数: dict, 上下文: dict = None) -> 操作结果:
        服务名 = 参数.get("服务名", "").strip()
        if not 服务名:
            return 操作结果.失败("请提供服务名称，如：3dsmax")

        管理器 = self.MCP管理器
        if not 管理器:
            return 操作结果.失败("MCP管理器未初始化")

        # 已连接则直接返回
        if 服务名 in 管理器.客户端列表:
            客户端 = 管理器.客户端列表[服务名]
            工具数 = len(客户端.工具列表)
            return 操作结果.成功(
                f"MCP服务 [{服务名}] 已连接，共 {工具数} 个工具可用。"
            )

        # 从注册中心获取操作注册中心实例（用于注册新工具）
        注册中心 = None
        if 上下文 and "操作注册中心" in 上下文:
            注册中心 = 上下文["操作注册中心"]
        elif hasattr(管理器, "_配置"):
            # 通过上下文获取不到时，从操作自身反查
            注册中心 = getattr(self, "_注册中心", None)

        if not 注册中心:
            # 尝试从管理器存储的引用获取
            注册中心 = getattr(管理器, "_注册目标", None)

        if not 注册中心:
            return 操作结果.失败("无法获取操作注册中心，工具注册失败")

        工具数 = 管理器.按名称连接(服务名, 注册中心)

        if 工具数 == -1:
            return 操作结果.失败(
                f"未找到名为 [{服务名}] 的MCP服务，请检查MCP服务.json配置"
            )
        elif 工具数 == 0:
            return 操作结果.失败(
                f"MCP服务 [{服务名}] 连接失败。可能原因：\n"
                f"1. 3ds Max未启动（请先打开3ds Max再连接）\n"
                f"2. MCP桥接插件未加载（首次连接需安装，可能需要1-2分钟，请重试）\n"
                f"3. uv包管理器安装失败（检查网络连接）\n"
                f"请确认3ds Max已打开后重试连接。"
            )
        else:
            return 操作结果.成功(
                f"MCP服务 [{服务名}] 连接成功！发现并注册 {工具数} 个工具，"
                f"现在可以通过自然语言控制3ds Max了。",
                元数据={"操作类型": "连接MCP服务", "工具数": 工具数, "服务名": 服务名}
            )
