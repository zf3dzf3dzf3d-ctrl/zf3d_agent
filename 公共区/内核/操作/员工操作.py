class 查询员工记忆(操作基类):
    名称 = "查询员工记忆"
    描述 = "查看某个员工的所有记忆内容。用户问'小李学到了什么''小王有什么经验'时使用。也用于排查员工行为异常。"
    参数结构 = {
        "姓名": {"类型": "字符串", "必填": True, "说明": "员工姓名，或'母体'"}
    }

    def 执行(self, 参数: dict) -> 操作结果:
        if not self.模块注册:
            return 操作结果.失败("模块注册未注入")
        模块 = self.模块注册.get("员工管理")
        if not 模块:
            return 操作结果.失败("员工管理模块未加载")
        姓名 = 参数.get("姓名", "")
        结果 = 模块.获取运行时配置(姓名)
        if not 结果.get("成功"):
            return 操作结果.失败(结果.get("错误", "员工不存在"))
        d = 结果["数据"]
        记忆路径 = d.get("记忆路径")
        if not 记忆路径:
            return 操作结果.成功(f"「{姓名}」使用共享记忆库（无独立记忆）")
        import json
        from pathlib import Path
        项目根 = Path(__file__).parent.parent.parent.parent
        绝对路径 = 项目根 / 记忆路径.lstrip("./")
        if not 绝对路径.exists():
            return 操作结果.成功(f"「{姓名}」暂无记忆记录（记忆文件不存在）")
        try:
            with open(绝对路径, "r", encoding="utf-8") as f:
                记忆数据 = json.load(f)
            if not 记忆数据:
                return 操作结果.成功(f"「{姓名}」记忆为空")
            汇总 = f"「{姓名}」记忆内容（{len(记忆数据)}条）：\n"
            for i, m in enumerate(记忆数据[-20:]):
                内容 = m if isinstance(m, str) else json.dumps(m, ensure_ascii=False)[:200]
                汇总 += f"  {i+1}. {内容[:200]}\n"
            return 操作结果.成功(汇总)
        except Exception as e:
            return 操作结果.失败(f"读取记忆失败: {e}")


class 修改员工记忆(操作基类):
    名称 = "修改员工记忆"
    描述 = "修改员工记忆内容。可以删除错误记忆、修正不正确的经验。用户说'清空小李的记忆''删除小王错误的记忆'时使用。"
    参数结构 = {
        "姓名": {"类型": "字符串", "必填": True, "说明": "员工姓名"},
        "操作": {"类型": "字符串", "必填": True, "说明": "清空/删除/替换。清空=全部删除，删除=按序号删除，替换=替换指定条目"},
        "序号": {"类型": "整数", "必填": False, "说明": "要删除/替换的记忆序号（从1开始）"},
        "新内容": {"类型": "字符串", "必填": False, "说明": "替换操作时的新内容"}
    }

    def 执行(self, 参数: dict) -> 操作结果:
        if not self.模块注册:
            return 操作结果.失败("模块注册未注入")
        模块 = self.模块注册.get("员工管理")
        if not 模块:
            return 操作结果.失败("员工管理模块未加载")
        姓名 = 参数.get("姓名", "")
        操作类型 = 参数.get("操作", "")
        结果 = 模块.获取运行时配置(姓名)
        if not 结果.get("成功"):
            return 操作结果.失败(结果.get("错误", "员工不存在"))
        d = 结果["数据"]
        记忆路径 = d.get("记忆路径")
        if not 记忆路径:
            return 操作结果.失败(f"「{姓名}」使用共享记忆库，无法独立修改")
        import json
        from pathlib import Path
        项目根 = Path(__file__).parent.parent.parent.parent
        绝对路径 = 项目根 / 记忆路径.lstrip("./")
        try:
            if 绝对路径.exists():
                with open(绝对路径, "r", encoding="utf-8") as f:
                    记忆数据 = json.load(f)
            else:
                记忆数据 = []
            if 操作类型 == "清空":
                记忆数据 = []
                msg = f"已清空「{姓名}」的全部记忆"
            elif 操作类型 == "删除":
                序号 = 参数.get("序号", 0)
                if 1 <= 序号 <= len(记忆数据):
                    del 记忆数据[序号 - 1]
                    msg = f"已删除「{姓名}」的第{序号}条记忆"
                else:
                    return 操作结果.失败(f"序号{序号}超出范围（共{len(记忆数据)}条）")
            elif 操作类型 == "替换":
                序号 = 参数.get("序号", 0)
                新内容 = 参数.get("新内容", "")
                if 1 <= 序号 <= len(记忆数据):
                    记忆数据[序号 - 1] = 新内容
                    msg = f"已替换「{姓名}」的第{序号}条记忆"
                else:
                    return 操作结果.失败(f"序号{序号}超出范围（共{len(记忆数据)}条）")
            else:
                return 操作结果.失败(f"未知操作: {操作类型}，支持: 清空/删除/替换")
            绝对路径.parent.mkdir(parents=True, exist_ok=True)
            with open(绝对路径, "w", encoding="utf-8") as f:
                json.dump(记忆数据, f, ensure_ascii=False, indent=2)
            return 操作结果.成功(msg)
        except Exception as e:
            return 操作结果.失败(f"修改记忆失败: {e}")


class 查询全体员工记忆(操作基类):
    名称 = "查询全体员工记忆"
    描述 = "查看所有员工的记忆摘要。用户说'看看所有员工学了什么''全员记忆检查'时使用。用于全局排查和学习效果评估。"
    参数结构 = {}

    def 执行(self, 参数: dict) -> 操作结果:
        if not self.模块注册:
            return 操作结果.失败("模块注册未注入")
        模块 = self.模块注册.get("员工管理")
        if not 模块:
            return 操作结果.失败("员工管理模块未加载")
        import json
        from pathlib import Path
        项目根 = Path(__file__).parent.parent.parent.parent
        列表结果 = 模块.获取员工列表()
        if not 列表结果.get("成功"):
            return 操作结果.失败("获取员工列表失败")
        汇总 = "全体员工记忆概览：\n"
        for emp in 列表结果["数据"]:
            姓名 = emp.get("姓名", "")
            if emp.get("是母体"):
                汇总 += f"\n👑 {姓名}（母体，使用共享记忆库）\n"
                continue
            运行时 = 模块.获取运行时配置(姓名)
            if not 运行时.get("成功"):
                continue
            d = 运行时["数据"]
            记忆路径 = d.get("记忆路径")
            if not 记忆路径:
                汇总 += f"\n{emp.get('头像','')} {姓名}（{emp.get('角色','')}）- 共享记忆\n"
                continue
            绝对路径 = 项目根 / 记忆路径.lstrip("./")
            if not 绝对路径.exists():
                汇总 += f"\n{emp.get('头像','')} {姓名}（{emp.get('角色','')}）- 无记忆记录\n"
                continue
            try:
                with open(绝对路径, "r", encoding="utf-8") as f:
                    记忆数据 = json.load(f)
                汇总 += f"\n{emp.get('头像','')} {姓名}（{emp.get('角色','')}）- {len(记忆数据)}条记忆\n"
                for m in 记忆数据[-3:]:
                    内容 = m if isinstance(m, str) else json.dumps(m, ensure_ascii=False)[:100]
                    汇总 += f"  · {内容[:100]}\n"
            except Exception:
                汇总 += f"\n{emp.get('头像','')} {姓名}（{emp.get('角色','')}）- 记忆读取失败\n"
        return 操作结果.成功(汇总)
