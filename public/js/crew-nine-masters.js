  /* 幂等注册：protocol 存储里没有该团队才创建（用户手动删除后不复活） */
  P.ensure = function () {
    try {
      if (!window.ZFCrewProtocol) return false;
      var list = ZFCrewProtocol.list ? ZFCrewProtocol.list() : [];
      var created = 0;
      TEAMS.forEach(function (t) {
        var exists = false;
        for (var i = 0; i < list.length; i++) { if (list[i].id === t.id) { exists = true; break; } }
        if (!exists) {
          var r = ZFCrewProtocol.exec('create', {
            id: t.id, name: t.name, author: t.author, desc: t.desc, roles: t.roles, silent: true
          });
          if (r && r.ok) created++;
        }
      });
      return true; // 三个团队检查完毕即成功（已存在的跳过）
    } catch (e) { try { console.warn('[nine-masters] 注册失败:', e); } catch (e2) {} return false; }
  };

  /* 协议加载器就绪后注入（双触发 + 轮询兜底，与 four-masters 同套路） */
  function boot() {
    if (!P.ensure()) {
      var tries = 0;
      var t = setInterval(function () {
        if (P.ensure() || ++tries > 20) clearInterval(t);
      }, 1000);
    }
  }
  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', boot);
  else boot();
