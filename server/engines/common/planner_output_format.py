# -*- coding: utf-8 -*-
"""server/engines/common/planner_output_format.py - 策划案输出格式单源常量

背景：策划师走不同链路（主对话派发/蜂群流水线/接棒按钮）时，system prompt
格式约束不一致，导致策划案格式漂移（有的按【任务计划/推荐度/策划师结论】
结构写，有的自由发挥）。本文件是唯一真源，各链路统一引用注入。

任何产出策划案的角色，其提示词末尾必须拼接 PLANNER_FORMAT_RULE。
"""

PLANNER_FORMAT_RULE = (
    '\n\n【策划案输出格式铁律（必备段缺一不可，含最终答复/task_complete 的 message 同样适用）】\n'
    '1.【任务计划】分阶段列出步骤（P0/P1...），标注收益与顺序；\n'
    '2.【推荐度】逐方案一行：「【推荐度】方案名 N/100（影响x·低成本x·低风险x·亮点x）｜档位S/A/B/C」；\n'
    '3.【实现方法】每个 P 的关键改法一句话；\n'
    '4.【策划师结论】①②③... 编号，可直接执行的落地清单，结尾标注【策划案路径：private/记忆/策划案-<主题>.md】；\n'
    '5. 策划案落盘文件名固定为「策划案-<主题>.md」（同一主题唯一真源，修订覆盖旧版不另起名）；\n'
    '6. 缺任一必备段视为不合格，必须按本模板重写后再输出。纯概念型可合并为一条整体推荐度；\n'
    '7.【反驳项】列出 1~3 条对自己方案的最强自我质疑（为什么可能失败/最易被审核员攻击的点/对应备选预案），'
    '每条一行「反N：质疑内容 → 应对」。缺此节视为不合格；审核员会逐条核验这些反驳项。'
)


def with_planner_format(text):
    """给任意策划师提示词追加格式铁律（供各链路调用）。"""
    return str(text or '') + PLANNER_FORMAT_RULE
