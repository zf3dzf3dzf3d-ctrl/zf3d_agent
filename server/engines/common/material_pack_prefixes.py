# -*- coding: utf-8 -*-
"""素材包前缀共享常量。

「策划师/审核员」自动发起的工作对话，首条用户消息以这些前缀开头。
提示词（public/prompts/.../用户问候.txt）与服务端检测
（server/mixin_proxy_joined_check.py）共用此处定义，避免双处硬编码漂移。
注意：修改前缀格式时，需同步更新 用户问候.txt 中的【重要例外】段落文字。
兼容：旧版前缀「（质检员素材包」「【质检员任务】」仍保留识别（历史对话存档兼容）。
"""

PACK_PREFIXES = (
    '（策划师素材包',
    '（审核员素材包',
    '【策划师任务】',
    '【审核员任务】',
    '（施工队素材包',   # ← 单源提醒：此处与 public/prompts/模式1_直接聊天/用户问候.txt 的【重要例外】段落必须同步修改
    '【施工队任务】',
    '（协作队素材包',   # ← 协作施工队（Crew 模式）前缀，与用户问候.txt 同步；与赛马施工队两条线互不串台
    '【协作队任务】',
    '（总结师素材包',   # ← 总结师（收口/总结阶段）前缀，与用户问候.txt 同步
    '【总结师任务】',
    '（策划方案·陈列',  # ← 策划师结论回注主对话的陈列标记：仅陈列方案供裁决，禁止自动开工
    # —— 旧版「质检员」前缀，仅保留识别，新链路一律产出「审核员」前缀 ——
    '（质检员素材包',
    '【质检员任务】',
)

# 策划方案陈列标记：主对话见到以此开头的消息，只做汇总对比，不得自动执行/开工
PLAN_DISPLAY_PREFIX = '（策划方案·陈列）'

GREETING_EXEMPT_MARK = '【重要例外】'

GREETING_EXEMPT_TEXT = (
    '\n\n【重要例外】本对话不是用户手动新建的普通对话，而是由「策划师/审核员/施工队/总结师」自动发起的工作对话。'
    '首条用户消息是自动生成的素材包，不是真人问候。'
    '完全忽略上方【用户问候】规则：不要问候、不要自报家门、不要问有什么可以帮忙，'
    '直接以素材包中指定的角色身份（策划师/审核员/施工队/总结师）开始执行任务。'
)


def is_material_pack_first_message(content) -> bool:
    """判断首条用户消息是否为素材包开头（含旧版「质检员」前缀兼容）。"""
    if not content:
        return False
    return str(content).startswith(PACK_PREFIXES)
